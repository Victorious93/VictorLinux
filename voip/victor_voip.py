#!/usr/bin/env python3
"""victor-voip: your own SIP server (Asterisk/PJSIP) for VictorSMS and other Victorious phones.

Security defaults: TLS 1.2+ only (no UDP/TCP listener), SRTP required, no anonymous/guest calls, every phone is a named endpoint with a
random 24-char password, per-phone PSTN permission, destination allow-list + concurrent-call cap against toll fraud. Secrets live in
<data>/secrets.json (0600) and are never printed except once by `add-device`/`provision`. Stdlib only; needs `asterisk` and `openssl`.

  victor-voip init  --host sip.example.org [--data DIR]      create CA-less self-signed cert, config skeleton
  victor-voip add-device NAME [--pstn]                       new extension + password, prints provisioning JSON ONCE
  victor-voip trunk --host H --user U [--prefix-in +1555..]  PSTN trunk (password via env VOIP_TRUNK_PASSWORD or stdin)
  victor-voip set --allow-prefix +1 --allow-prefix +44 --max-pstn 2 --inbound-ext 1001
  victor-voip render                                         write asterisk conf files (done automatically by the commands above)
  victor-voip run [--foreground]                             run asterisk against this config
"""
import argparse, json, os, secrets, string, subprocess, sys

ALPH = string.ascii_letters + string.digits


def data_dir(a=None):
    return os.path.abspath((a and getattr(a, "data", None)) or os.environ.get("VICTOR_VOIP_DIR") or os.path.expanduser("~/.local/share/victor-voip"))


def load(d):
    try:
        return json.load(open(os.path.join(d, "secrets.json")))
    except FileNotFoundError:
        sys.exit("not initialised: run `victor-voip init --host HOST` first")


def save(d, s):
    p = os.path.join(d, "secrets.json"); tmp = p + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f: json.dump(s, f, indent=2)
    os.replace(tmp, p)


def valid_name(n): return bool(n) and len(n) <= 32 and all(c.isalnum() or c in "-_" for c in n)
def valid_host(h): return bool(h) and len(h) < 254 and all(c.isalnum() or c in ".-" for c in h)
def valid_prefix(p): return p.startswith("+") and p[1:].isdigit() and len(p) <= 8


def render(d):
    s = load(d); p = os.path.join(d, "etc"); os.makedirs(p, exist_ok=True)
    tls = os.path.join(d, "tls")
    port = s["port"]
    pj = [f"""; generated by victor-voip -- do not edit
[global]
type=global
endpoint_identifier_order=auth_username,username,ip
unidentified_request_count=5
unidentified_request_period=5
unidentified_request_prune_interval=30

[transport-tls]
type=transport
protocol=tls
bind=0.0.0.0:{port}
cert_file={tls}/server.crt
priv_key_file={tls}/server.key
method=tlsv1_2
verify_client=no
verify_server=no
external_signaling_address={s['host']}
external_media_address={s['host']}
local_net=10.0.0.0/8
local_net=172.16.0.0/12
local_net=192.168.0.0/16
"""]
    for n, dev in s["devices"].items():
        e = dev["ext"]
        pj.append(f"""
[{e}]
type=endpoint
context=from-phones
disallow=all
allow=opus,ulaw,alaw
transport=transport-tls
auth={e}-auth
aors={e}
media_encryption=sdes
media_encryption_optimistic=no
direct_media=no
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes
callerid="{n}" <{e}>
set_var=PSTN_OK={1 if dev.get('pstn') else 0}

[{e}-auth]
type=auth
auth_type=userpass
username={e}
password={dev['password']}

[{e}]
type=aor
max_contacts=3
remove_existing=yes
qualify_frequency=60
""")
    t = s.get("trunk")
    if t:
        pj.append(f"""
[trunk]
type=endpoint
context=from-trunk
disallow=all
allow=ulaw,alaw
outbound_auth=trunk-auth
aors=trunk
direct_media=no
media_encryption={'sdes' if t.get('srtp', True) else 'no'}
from_user={t['user']}
rtp_symmetric=yes
force_rport=yes

[trunk-auth]
type=auth
auth_type=userpass
username={t['user']}
password={t['password']}

[trunk]
type=aor
contact=sip:{t['host']}

[trunk-reg]
type=registration
outbound_auth=trunk-auth
server_uri=sip:{t['host']}
client_uri=sip:{t['user']}@{t['host']}
retry_interval=60

[trunk-id]
type=identify
endpoint=trunk
match={t['host']}
""")
    open(os.path.join(p, "pjsip.conf"), "w").write("".join(pj))
    allow = s["allow_prefixes"]
    pat = "\n".join(f"exten => _{pre}X.,1,Goto(pstn-out,${{EXTEN}},1)" for pre in allow)
    exts = "\n".join(f"exten => {dev['ext']},1,NoOp()\n same => n,Dial(PJSIP/{dev['ext']},30)\n same => n,Hangup()" for n, dev in s["devices"].items())
    inbound = s.get("inbound_ext")
    conf = f"""; generated by victor-voip
[general]
static=yes
writeprotect=yes

[from-phones]
{exts}
{pat}
exten => _X.,1,NoOp(Rejected: unknown destination)
 same => n,Playback(ss-noservice)
 same => n,Hangup()

[pstn-out]
exten => _+X.,1,NoOp()
 same => n,GotoIf($["${{PSTN_OK}}"="1"]?ok:deny)
 same => n(deny),Playback(ss-noservice)
 same => n,Hangup()
 same => n(ok),Set(GROUP()=pstn)
 same => n,GotoIf($[${{GROUP_COUNT(pstn)}}>{s['max_pstn']}]?busy)
 same => n,Dial(PJSIP/${{EXTEN}}@trunk,60)
 same => n,Hangup()
 same => n(busy),Busy(10)

[from-trunk]
exten => _X.,1,NoOp(inbound PSTN)
{f' same => n,Dial(PJSIP/{inbound_target(s, inbound)},40)' if inbound else ' same => n,Playback(ss-noservice)'}
 same => n,Hangup()
"""
    open(os.path.join(p, "extensions.conf"), "w").write(conf)
    open(os.path.join(p, "asterisk.conf"), "w").write(f"""[directories]
astetcdir => {p}
astvarlibdir => /var/lib/asterisk
astmoddir => {moddir()}
astspooldir => {d}/spool
astrundir => {d}/run
astlogdir => {d}/log
astdbdir => {d}/run
[options]
runuser = {os.environ.get('USER', 'root')}
""")
    open(os.path.join(p, "modules.conf"), "w").write("[modules]\nautoload=yes\n" + "".join(f"noload={m}.so\n" for m in ("chan_sip", "res_hep", "res_hep_pjsip", "res_hep_rtcp", "res_pjsip_config_wizard", "res_pjsip_phoneprov_provider", "res_phoneprov", "res_ari", "app_amd", "app_followme", "res_prometheus", "app_queue", "res_pjsip_notify")))
    open(os.path.join(p, "rtp.conf"), "w").write("[general]\nrtpstart=10000\nrtpend=10200\nicesupport=no\nstrictrtp=yes\n")
    open(os.path.join(p, "logger.conf"), "w").write(f"[general]\n[logfiles]\nconsole => notice,warning,error,verbose\nfull => notice,warning,error,verbose,debug\n")
    for sub in ("spool", "run", "log"): os.makedirs(os.path.join(d, sub), exist_ok=True)
    return p


def moddir():
    for c in ("/usr/lib/x86_64-linux-gnu/asterisk/modules", "/usr/lib/aarch64-linux-gnu/asterisk/modules", "/usr/lib/asterisk/modules", "/usr/lib64/asterisk/modules"):
        if os.path.exists(os.path.join(c, "res_pjsip.so")): return c
    return "/usr/lib/asterisk/modules"


def inbound_target(s, ext):
    for n, dev in s["devices"].items():
        if dev["ext"] == ext: return dev['ext']
    sys.exit(f"inbound extension {ext} is not a device")


def init(a):
    d = data_dir(a)
    if not valid_host(a.host): sys.exit("bad host")
    os.makedirs(os.path.join(d, "tls"), mode=0o700, exist_ok=True)
    crt, key = os.path.join(d, "tls/server.crt"), os.path.join(d, "tls/server.key")
    if not os.path.exists(crt):
        san = "IP" if all(c.isdigit() or c == "." for c in a.host) else "DNS"
        subprocess.run(["openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:prime256v1", "-nodes", "-days", "3650", "-keyout", key, "-out", crt,
                        "-subj", f"/CN={a.host}", "-addext", f"subjectAltName={san}:{a.host}"], check=True, capture_output=True)
        os.chmod(key, 0o600)
    fp = subprocess.run(["openssl", "x509", "-in", crt, "-noout", "-fingerprint", "-sha256"], capture_output=True, text=True, check=True).stdout.strip().split("=", 1)[1]
    s = {"host": a.host, "port": a.port, "fingerprint_sha256": fp, "devices": {}, "allow_prefixes": ["+1"], "max_pstn": 2, "next_ext": 1001}
    if os.path.exists(os.path.join(d, "secrets.json")): sys.exit("already initialised (delete the data dir to start over)")
    save(d, s); render(d); print(f"initialised {d}\nserver TLS fingerprint (phones pin this): {fp}")


def add_device(a):
    d = data_dir(a); s = load(d)
    if not valid_name(a.name) or a.name in s["devices"] or a.name == "trunk": sys.exit("bad or duplicate device name")
    ext = str(s["next_ext"]); s["next_ext"] += 1
    pw = "".join(secrets.choice(ALPH) for _ in range(24))
    s["devices"][a.name] = {"ext": ext, "password": pw, "pstn": bool(a.pstn)}
    save(d, s); render(d)
    print(json.dumps(provision_doc(s, a.name), indent=2))
    print("# shown once: enter these in VictorSMS → Settings → SIP / VoIP", file=sys.stderr)


def provision_doc(s, name):
    dev = s["devices"][name]
    return {"domain": s["host"], "port": s["port"], "transport": "tls", "username": dev["ext"], "password": dev["password"], "display_name": name,
            "srtp": "required", "server_cert_sha256": s["fingerprint_sha256"]}


def trunk(a):
    d = data_dir(a); s = load(d)
    pw = os.environ.get("VOIP_TRUNK_PASSWORD") or sys.stdin.readline().strip()
    if not (valid_host(a.host) and valid_name(a.user.replace("+", "").replace(".", "").replace("@", "")) and pw): sys.exit("host, user and password (env VOIP_TRUNK_PASSWORD or stdin) required")
    s["trunk"] = {"host": a.host, "user": a.user, "password": pw, "srtp": not a.no_srtp}
    save(d, s); render(d); print("trunk configured (password stored in secrets.json, 0600)")


def setcmd(a):
    d = data_dir(a); s = load(d)
    if a.allow_prefix:
        if not all(valid_prefix(p) for p in a.allow_prefix): sys.exit("prefixes look like +1 or +44")
        s["allow_prefixes"] = a.allow_prefix
    if a.max_pstn is not None: s["max_pstn"] = max(1, min(a.max_pstn, 20))
    if a.inbound_ext: inbound_target(s, a.inbound_ext); s["inbound_ext"] = a.inbound_ext
    save(d, s); render(d); print("ok")


def run(a):
    d = data_dir(a); render(d)
    cmd = ["asterisk", "-C", os.path.join(d, "etc/asterisk.conf"), "-f" if a.foreground else "-F"]
    os.execvp(cmd[0], cmd)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="victor-voip"); ap.add_argument("--data")
    sp = ap.add_subparsers(dest="c", required=True)
    i = sp.add_parser("init"); i.add_argument("--host", required=True); i.add_argument("--port", type=int, default=5061)
    x = sp.add_parser("add-device"); x.add_argument("name"); x.add_argument("--pstn", action="store_true")
    t = sp.add_parser("trunk"); t.add_argument("--host", required=True); t.add_argument("--user", required=True); t.add_argument("--no-srtp", action="store_true")
    z = sp.add_parser("set"); z.add_argument("--allow-prefix", action="append"); z.add_argument("--max-pstn", type=int); z.add_argument("--inbound-ext")
    sp.add_parser("render"); r = sp.add_parser("run"); r.add_argument("--foreground", action="store_true")
    a = ap.parse_args(argv)
    {"init": init, "add-device": add_device, "trunk": trunk, "set": setcmd, "render": lambda a: print(render(data_dir(a))), "run": run}[a.c](a)


if __name__ == "__main__":
    main()
